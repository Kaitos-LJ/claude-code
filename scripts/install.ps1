#Requires -Version 5.1
<#
    Install cc (this project's restored Claude Code CLI) on Windows.

    Normally you do not run this file directly - double-click
    scripts\install.cmd instead, which calls this script for you.

        scripts\install.cmd
        scripts\install.cmd --no-deps
        scripts\install.cmd --no-build
        scripts\install.cmd --no-path

    Environment variables:
        CC_BIN_NAME      launcher command name          (default: cc)
        CC_INSTALL_DIR   launcher directory             (default: %LOCALAPPDATA%\Programs\cc\bin)
#>
param(
    [Parameter(ValueFromRemainingArguments = $true)]
    [string[]]$Arguments = @()
)

$ErrorActionPreference = 'Stop'

$runDeps = $true
$runBuild = $true
$runPath = $true

foreach ($arg in $Arguments) {
    switch ($arg) {
        '--no-deps' { $runDeps = $false }
        '--no-build' { $runBuild = $false }
        '--no-path' { $runPath = $false }
        { $_ -in @('-h', '--help', '/?') } {
            Write-Host 'Usage: scripts\install.cmd [--no-deps] [--no-build] [--no-path]'
            Write-Host ''
            Write-Host '  --no-deps    skip "bun install"'
            Write-Host '  --no-build   skip "bun run build"'
            Write-Host '  --no-path    do not add the launcher directory to the user PATH'
            Write-Host ''
            Write-Host 'Environment: CC_BIN_NAME (default: cc)'
            Write-Host '             CC_INSTALL_DIR (default: %LOCALAPPDATA%\Programs\cc\bin)'
            exit 0
        }
        default {
            Write-Host "[ERROR] Unknown argument: $arg" -ForegroundColor Red
            exit 1
        }
    }
}

$binName = if ($env:CC_BIN_NAME) { $env:CC_BIN_NAME } else { 'cc' }
$installDir = if ($env:CC_INSTALL_DIR) { $env:CC_INSTALL_DIR } else { Join-Path $env:LOCALAPPDATA 'Programs\cc\bin' }
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path

# --- Prerequisite: bun ------------------------------------------------------
$bun = Get-Command bun -ErrorAction SilentlyContinue
if (-not $bun) {
    Write-Host '[ERROR] "bun" was not found on this machine.' -ForegroundColor Red
    Write-Host ''
    Write-Host 'Install Bun first - paste this single line into PowerShell and press Enter:'
    Write-Host ''
    Write-Host '    irm bun.sh/install.ps1 | iex' -ForegroundColor Yellow
    Write-Host ''
    Write-Host 'Then CLOSE that window, open a new one, and run this installer again.'
    exit 1
}

Write-Host "==> bun $(& bun --version)  |  repo: $root"

Push-Location $root
try {
    if ($runDeps) {
        Write-Host '==> Installing dependencies (bun install)'
        & bun install
        if ($LASTEXITCODE -ne 0) { throw "bun install failed (exit code $LASTEXITCODE)" }
    }
    if ($runBuild) {
        Write-Host '==> Building (bun run build)'
        & bun run build
        if ($LASTEXITCODE -ne 0) { throw "bun run build failed (exit code $LASTEXITCODE)" }
    }
}
finally {
    Pop-Location
}

$bundle = Join-Path $root 'dist\cli.js'
if (-not (Test-Path -LiteralPath $bundle)) {
    Write-Host "[ERROR] Build output not found: $bundle" -ForegroundColor Red
    Write-Host '        Run the installer without --no-build.'
    exit 1
}

# --- Write the launcher -----------------------------------------------------
if (-not (Test-Path -LiteralPath $installDir)) {
    New-Item -ItemType Directory -Path $installDir -Force | Out-Null
}

$launcher = Join-Path $installDir "$binName.cmd"
# Written line-by-line so Set-Content uses the platform newline (CRLF on
# Windows), and in the console/OEM code page so non-ASCII paths survive.
$launcherBody = @(
    '@echo off',
    "rem Generated by $PSCommandPath",
    "bun `"$bundle`" %*"
)
Set-Content -LiteralPath $launcher -Value $launcherBody -Encoding OEM

Write-Host "==> Launcher installed: $launcher"
Write-Host "    runs: bun `"$bundle`""

# --- Add the launcher directory to the user PATH ----------------------------
if ($runPath) {
    try {
        $userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
        if ($null -eq $userPath) { $userPath = '' }
        if (($userPath -split ';') -contains $installDir) {
            Write-Host '==> PATH already contains the launcher directory'
        }
        else {
            $newPath = ($userPath.TrimEnd(';') + ';' + $installDir).TrimStart(';')
            [Environment]::SetEnvironmentVariable('Path', $newPath, 'User')
            Write-Host '==> Added to your user PATH (open a NEW terminal for it to take effect)'
        }
    }
    catch {
        Write-Host "[WARN] Could not update PATH automatically: $($_.Exception.Message)" -ForegroundColor Yellow
        Write-Host "       Add this directory to PATH yourself: $installDir"
    }
}

# --- Smoke test -------------------------------------------------------------
Write-Host '==> Version check:'
$smokeFailed = $false
try {
    & $launcher --version
    if ($LASTEXITCODE -ne 0) { $smokeFailed = $true }
}
catch {
    Write-Host $_.Exception.Message -ForegroundColor Red
    $smokeFailed = $true
}
if ($smokeFailed) {
    Write-Host "[ERROR] The launcher was installed but '$binName --version' failed." -ForegroundColor Red
    Write-Host "        Try running it directly: `"$launcher`" --version"
    exit 1
}

Write-Host ''
Write-Host "Done. Open a NEW terminal window and run:  $binName" -ForegroundColor Green
Write-Host "Uninstall: delete `"$launcher`""
exit 0
